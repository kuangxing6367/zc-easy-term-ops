#!/bin/bash
# ============================================================
# 文件：plugins/example_plugin.sh
# 功能：插件示例模板 [Plugin Template]
# 作者：zc 团队
# 版本：1.0.0
# 日期：2026-08-05
# 说明：
#   - 插件命名格式：<序号>_<名称>.sh（如 01_my_tools.sh）
#   - 放入 plugins/ 目录后主菜单自动扫描并动态加载
#   - 必须实现 plugin_name / plugin_menu() / plugin_execute()
#   - 可安全调用 core 库：log_* / check_command / confirm_action 等
# ============================================================
set -euo pipefail

# 插件显示名称（主菜单展示）
plugin_name="示例插件(Example)"

# ------------------------------------------------------------
# 插件描述（进入插件时显示）
# 参数：无
# 返回：无
# ------------------------------------------------------------
plugin_description() {
    echo "这是一个插件示例模板，展示插件开发规范"
}

# ------------------------------------------------------------
# 插件子菜单
# 参数：无
# 返回：无
# ------------------------------------------------------------
plugin_menu() {
    echo "======================================"
    echo "  ${plugin_name} 子菜单"
    echo "======================================"
    echo " 1. 系统信息展示"
    echo " 2. 当前磁盘占用"
    echo " 0. 返回主菜单"
    echo "======================================"
}

# ------------------------------------------------------------
# 插件执行入口（参数为子菜单选项）
# 参数：$1 选项数字
# 返回：0=继续 非0/返回=退出子菜单
# ------------------------------------------------------------
plugin_execute() {
    local choice="$1"
    case "${choice}" in
        1) plugin_show_sysinfo ;;
        2) plugin_show_disk ;;
        0) return 0 ;;
        *) log_error "无效选项: ${choice}" ;;
    esac
    press_enter
}

# ------------------------------------------------------------
# 展示系统信息
# 参数：无
# 返回：无
# ------------------------------------------------------------
plugin_show_sysinfo() {
    log_info "系统信息展示"
    echo "  发行版: $(get_distro)"
    echo "  内核:   $(uname -r)"
    echo "  架构:   $(get_arch)"
    echo "  包管理: $(detect_pkg_manager)"
    echo "  运行时长: $(uptime -p 2>/dev/null || echo 'N/A')"
}

# ------------------------------------------------------------
# 展示磁盘占用
# 参数：无
# 返回：无
# ------------------------------------------------------------
plugin_show_disk() {
    log_info "磁盘占用（df -h）"
    df -h || true
}
